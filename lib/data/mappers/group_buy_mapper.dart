import '../../domain/entities/group_buy.dart';
import '../../domain/enums/sponsor_type.dart';
import '../models/group_buy_model.dart';

/// Mapper for converting between [GroupBuyModel] and [GroupBuy].
class GroupBuyMapper {
  static GroupBuy toEntity(GroupBuyModel model) {
    return GroupBuy(
      id: model.id,
      title: model.title,
      description: model.description,
      linkedListingId: model.linkedListingId,
      organizerId: model.organizerId,
      organizerName: model.organizerName,
      communityId: model.communityId,
      targetAmount: model.targetAmount,
      currentAmount: model.currentAmount,
      minParticipants: model.minParticipants,
      maxParticipants: model.maxParticipants,
      deadline: model.deadline,
      status: model.status,
      participantCount: model.participantCount,
      sponsorType: SponsorType.fromString(model.sponsorType),
      brandId: model.brandId,
      brandName: model.brandName,
      brandLogoUrl: model.brandLogoUrl,
      discountPercent: model.discountPercent,
      createdByAdmin: model.createdByAdmin,
      type: model.type,
      fulfilmentType: model.fulfilmentType,
      clusters: model.clusters,
      addresses: model.addresses,
      voucherCodes: model.voucherCodes,
      imageUrl: model.imageUrl,
      originalPrice: model.originalPrice,
      collectionDeadline: model.collectionDeadline,
      deliveryStatus: model.deliveryStatus,
      fulfilmentInstructions: model.fulfilmentInstructions,
      collectedCount: model.collectedCount,
      category: model.category,
      deliveryFee: model.deliveryFee,
      organizerSuccessRate: model.organizerSuccessRate,
      createdAt: model.createdAt,
      updatedAt: model.updatedAt,
    );
  }

  static GroupBuyModel fromEntity(GroupBuy entity) {
    return GroupBuyModel(
      id: entity.id,
      title: entity.title,
      description: entity.description,
      linkedListingId: entity.linkedListingId,
      organizerId: entity.organizerId,
      organizerName: entity.organizerName,
      communityId: entity.communityId,
      targetAmount: entity.targetAmount,
      currentAmount: entity.currentAmount,
      minParticipants: entity.minParticipants,
      maxParticipants: entity.maxParticipants,
      deadline: entity.deadline,
      status: entity.status,
      participantCount: entity.participantCount,
      sponsorType: entity.sponsorType.name,
      brandId: entity.brandId,
      brandName: entity.brandName,
      brandLogoUrl: entity.brandLogoUrl,
      discountPercent: entity.discountPercent,
      createdByAdmin: entity.createdByAdmin,
      type: entity.type,
      fulfilmentType: entity.fulfilmentType,
      clusters: entity.clusters,
      addresses: entity.addresses,
      voucherCodes: entity.voucherCodes,
      imageUrl: entity.imageUrl,
      originalPrice: entity.originalPrice,
      collectionDeadline: entity.collectionDeadline,
      deliveryStatus: entity.deliveryStatus,
      fulfilmentInstructions: entity.fulfilmentInstructions,
      collectedCount: entity.collectedCount,
      category: entity.category,
      deliveryFee: entity.deliveryFee,
      organizerSuccessRate: entity.organizerSuccessRate,
      createdAt: entity.createdAt,
      updatedAt: entity.updatedAt,
    );
  }
}
